/** 需要二次确认的破坏性操作。 */
private enum class ConfirmKind { NONE, CLEAR_DEVICE }

/**
 * 同步配置页（M3.2 前半）：未配置 → 已登录 的单一状态机。
 *
 * 入口：
 * - 设置 → 同步配置；
 * - `vkey://config?server=…` 深链 / 扫码（自动填地址）；
 * - `vkey://pair?code=…` 深链 / 扫码（自动填配对码）。
 *
 * 所有网络与密码学操作都在 IO 线程执行，结果通过 [onSaved] 落盘。
 *
 * @param masterKey 当前库的 master_key（base32），用于生成配对码与校正账号密钥
 * @param device 已保存的设备材料；null 表示未配置
 * @param serverUrl 当前设置的同步服务地址
 * @param initialPairCode 从扫码/深链带进来的配对码（可为 null）
 * @param onSaved 配置成功回调：新设备材料 + 需要替换的 master_key（null 表示与本地一致）
 * @param onServerUrlChange 服务器地址变化（持久化到 AppSettings）
 * @param onClearDevice 断开配对（清除设备材料）
 * @param onClose 关闭本页
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SyncScreen(
    masterKey: String,
    device: DeviceConfig?,
    serverUrl: String,
    initialPairCode: String?,
    onSaved: (DeviceConfig, String?) -> Unit,
    onServerUrlChange: (String) -> Unit,
    onClearDevice: () -> Unit,
    onClose: () -> Unit,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var url by remember { mutableStateOf(serverUrl) }
    var deviceName by remember { mutableStateOf(device?.device_name ?: defaultDeviceName()) }
    var masterKeyInput by remember { mutableStateOf("") }
    var pairCodeInput by remember { mutableStateOf(initialPairCode.orEmpty()) }
    var busy by remember { mutableStateOf<String?>(null) }
    var error by remember { mutableStateOf<String?>(null) }
    var info by remember { mutableStateOf<String?>(null) }
    var showScan by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<GeneratedPairCode?>(null) }
    var remainingSeconds by remember { mutableLongStateOf(0L) }
    var confirm by remember { mutableStateOf(ConfirmKind.NONE) }

    /** 统一的任务执行：置忙、清错误、切 IO。 */
    val runTask: (String, suspend () -> Unit) -> Unit = { label, task ->
        if (busy == null) {
            error = null
            info = null
            busy = label
            scope.launch {
                try {
                    task()
                } catch (t: Throwable) {
                    error = describeFailure(t)
                } finally {
                    busy = null
                }
            }
        }
    }

    /** 用 master_key 登录。 */
    val doLogin: () -> Unit = {
        val mk = masterKeyInput.trim()
        val address = url.trim()
        when {
            busy != null -> Unit
            address.isEmpty() -> error = "请先填写服务器地址"
            !SyncManager.looksLikeKey(mk) -> error = "master_key 必须是 52 位 base32（可用空格/连字符分组）"
            else -> runTask("正在用主密钥登录…") {
                val result = withContext(Dispatchers.IO) {
                    SyncManager.login(address, mk, deviceName, device?.seed)
                }
                onServerUrlChange(result.config.server_url)
                onSaved(result.config, result.masterKeyBase32.takeIf { it != masterKey })
                masterKeyInput = ""
                info = "已登录：${result.config.device_name}"
            }
        }
    }

    /** 用配对码领取 master_key。 */
    val doPair: () -> Unit = {
        val code = pairCodeInput.trim()
        val address = url.trim()
        when {
            busy != null -> Unit
            address.isEmpty() -> error = "请先填写服务器地址"
            !SyncManager.looksLikeKey(code) -> error = "配对码必须是 52 位 base32（可用空格/连字符分组）"
            else -> runTask("正在领取配对码…") {
                val result = withContext(Dispatchers.IO) {
                    SyncManager.pair(address, code, deviceName, device?.seed)
                }
                onServerUrlChange(result.config.server_url)
                onSaved(result.config, result.masterKeyBase32.takeIf { it != masterKey })
                pairCodeInput = ""
                info = "配对成功：${result.config.device_name}"
            }
        }
    }

    /** 生成配对码（需要已登录 + 已解锁）。 */
    val doGenerate: () -> Unit = {
        val cfg = device
        when {
            busy != null || cfg == null -> Unit
            else -> runTask("正在生成配对码…") {
                val pairCode = withContext(Dispatchers.IO) {
                    SyncManager.generatePairCode(cfg, masterKey)
                }
                generated = pairCode
                remainingSeconds = (pairCode.expiresAt - System.currentTimeMillis() / 1000).coerceAtLeast(0)
            }
        }
    }

    // 配对码有效期倒计时：以服务端 expires_at 为准，逐秒刷新
    LaunchedEffect(generated) {
        val expiresAt = generated?.expiresAt ?: return@LaunchedEffect
        while (true) {
            remainingSeconds = (expiresAt - System.currentTimeMillis() / 1000).coerceAtLeast(0)
            if (remainingSeconds <= 0L) break
            delay(1_000)
        }
    }

    val pairedServer = device?.server_url
    val serverChanged = pairedServer != null && normalizeUrl(url) != normalizeUrl(pairedServer)

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("同步配置") },
                navigationIcon = { TextButton(onClick = onClose) { Text("返回") } },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            // ---------------- 状态 ----------------
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp)) {
                    Text(
                        text = if (device == null) "未配置" else "已登录",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Medium,
                    )
                    if (device == null) {
                        Text(
                            "输入 master_key 或配对码完成配置；也可以先扫服务端二维码自动填好地址。",
                            style = MaterialTheme.typography.bodySmall,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                    } else {
                        Text("设备：${device.device_name}", style = MaterialTheme.typography.bodySmall)
                        Text("服务器：${device.server_url}", style = MaterialTheme.typography.bodySmall)
                        Text("账号：${device.username}", style = MaterialTheme.typography.bodySmall)
                    }
                }
            }

            if (busy != null) {
                LinearProgressIndicator(modifier = Modifier.fillMaxWidth())
                Text(busy.orEmpty(), style = MaterialTheme.typography.bodySmall)
            }
            info?.let {
                Text(it, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.primary)
            }
            error?.let {
                Text(it, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.error)
            }

            // ---------------- 服务器地址 ----------------
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp)) {
                    OutlinedTextField(
                        value = url,
                        onValueChange = { url = it },
                        label = { Text("同步服务地址") },
                        singleLine = true,
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Uri),
                        modifier = Modifier.fillMaxWidth(),
                    )
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Button(
                            onClick = {
                                onServerUrlChange(url)
                                info = "服务器地址已保存"
                            },
                            enabled = busy == null && url.trim().isNotEmpty(),
                            modifier = Modifier.weight(1f),
                        ) { Text("保存地址") }
                        Button(
                            onClick = { showScan = true },
                            enabled = busy == null,
                            modifier = Modifier.weight(1f),
                        ) { Text("扫码") }
                    }
                    Text(
                        "扫码可识别服务端 /pair 或主页的二维码（内容只有服务器地址）",
                        style = MaterialTheme.typography.bodySmall,
                        modifier = Modifier.padding(top = 4.dp),
                    )
                }
            }

            if (device != null) {
                // ---------------- 已登录：生成配对码 ----------------
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) {
                        Text("给新设备配对", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "生成一次性配对码（10 分钟内有效、单次可用）。在新设备输入它，或扫描它的二维码内容即可接入同一账号。",
                            style = MaterialTheme.typography.bodySmall,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                        Spacer(Modifier.height(8.dp))
                        Button(
                            onClick = doGenerate,
                            enabled = busy == null,
                            modifier = Modifier.fillMaxWidth(),
                        ) { Text(if (generated == null) "生成配对码" else "重新生成") }

                        val pairCode = generated
                        if (pairCode != null) {
                            Spacer(Modifier.height(12.dp))
                            Text(
                                text = pairCode.codeText,
                                fontFamily = FontFamily.Monospace,
                                fontSize = 17.sp,
                                fontWeight = FontWeight.Medium,
                            )
                            Text(
                                text = if (remainingSeconds > 0) {
                                    "剩余有效期 ${formatCountdown(remainingSeconds)}"
                                } else {
                                    "已过期，请重新生成"
                                },
                                style = MaterialTheme.typography.bodySmall,
                                color = if (remainingSeconds > 0) {
                                    MaterialTheme.colorScheme.primary
                                } else {
                                    MaterialTheme.colorScheme.error
                                },
                                modifier = Modifier.padding(top = 4.dp),
                            )
                            Spacer(Modifier.height(4.dp))
                            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                Button(
                                    onClick = {
                                        copyToClipboard(context, pairCode.codeText, sensitive = false)
                                        info = "配对码已复制"
                                    },
                                    enabled = remainingSeconds > 0,
                                ) { Text("复制配对码") }
                                TextButton(onClick = { showScan = true }) { Text("去扫码") }
                            }
                        }
                    }
                }

                HorizontalDivider()

                // ---------------- 切服务器 / 断开 ----------------
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) {
                        Text("设备管理", style = MaterialTheme.typography.titleMedium)
                        if (serverChanged) {
                            Text(
                                "填写的地址与当前配对不一致：更换服务器后需要重新配对。",
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.error,
                                modifier = Modifier.padding(top = 4.dp),
                            )
                        }
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = deviceName,
                            onValueChange = { deviceName = it },
                            label = { Text("设备名（重新配对时使用）") },
                            singleLine = true,
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Spacer(Modifier.height(8.dp))
                        TextButton(
                            onClick = { confirm = ConfirmKind.CLEAR_DEVICE },
                            enabled = busy == null,
                        ) { Text("断开配对（清除本机设备材料）") }
                    }
                }
            } else {
                // ---------------- 未配置：两条配置路径 ----------------
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) {
                        Text("用 master_key 登录", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "恢复码 / master_key（52 位）。本机会生成并保存自己的设备密钥。",
                            style = MaterialTheme.typography.bodySmall,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = masterKeyInput,
                            onValueChange = { masterKeyInput = it },
                            label = { Text("master_key") },
                            singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Spacer(Modifier.height(8.dp))
                        Button(
                            onClick = doLogin,
                            enabled = busy == null,
                            modifier = Modifier.fillMaxWidth(),
                        ) { Text("用 master_key 完成配置") }
                    }
                }

                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) {
                        Text("用配对码领取", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "在已登录的设备上「生成配对码」，把 52 位配对码输入这里。配对成功后本机主密钥以账号为准（本机已有条目保留）。",
                            style = MaterialTheme.typography.bodySmall,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = pairCodeInput,
                            onValueChange = { pairCodeInput = it },
                            label = { Text("配对码（可含 - 与空格）") },
                            singleLine = true,
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Ascii),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Spacer(Modifier.height(8.dp))
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            Button(
                                onClick = doPair,
                                enabled = busy == null,
                                modifier = Modifier.weight(1f),
                            ) { Text("领取并完成配置") }
                            Button(
                                onClick = { showScan = true },
                                enabled = busy == null,
                                modifier = Modifier.weight(1f),
                            ) { Text("扫码输入") }
                        }
                    }
                }

                OutlinedTextField(
                    value = deviceName,
                    onValueChange = { deviceName = it },
                    label = { Text("设备名") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                )
            }
        }
    }

    if (showScan) {
        ScanScreen(
            onResult = null,
            onConfigLink = { server ->
                url = server
                onServerUrlChange(server)
                showScan = false
                info = "服务器地址已设置：$server"
            },
            onPairCode = { code ->
                pairCodeInput = code
                showScan = false
                info = "已识别配对码，点「领取并完成配置」继续"
            },
            onCancel = { showScan = false },
        )
    }

    if (confirm == ConfirmKind.CLEAR_DEVICE) {
        AlertDialog(
            onDismissRequest = { confirm = ConfirmKind.NONE },
            title = { Text("断开配对？") },
            text = {
                Text("只清除本机的 token 与设备密钥，不影响服务端条目和其它设备。之后可重新配对。")
            },
            confirmButton = {
                TextButton(onClick = {
                    confirm = ConfirmKind.NONE
                    generated = null
                    onClearDevice()
                    onServerUrlChange(url)
                    info = "已断开配对"
                }) { Text("断开") }
            },
            dismissButton = {
                TextButton(onClick = { confirm = ConfirmKind.NONE }) { Text("取消") }
            },
        )
    }
}

/** 默认设备名：`Android <型号>`（型号可能为空，退化为 `android`）。 */
private fun defaultDeviceName(): String {
    val model = Build.MODEL.orEmpty().trim()
    return SyncManager.sanitizeDeviceName(if (model.isEmpty()) "android" else "Android $model")
}

/** 去掉尾部斜杠用于比较服务器地址。 */
private fun normalizeUrl(url: String): String = url.trim().trimEnd('/')

/** 把剩余秒数格式化为 `mm:ss`。 */
private fun formatCountdown(seconds: Long): String {
    val safe = seconds.coerceAtLeast(0)
    return "%02d:%02d".format(safe / 60, safe % 60)
}

/**
 * 把底层异常翻译成用户能看懂的一句话。
 *
 * @param t 捕获到的异常
 * @return 中文说明（保留服务端错误码便于排查）
 */
private fun describeFailure(t: Throwable): String {
    if (t is ApiException) {
        val hint = when (t.code) {
            "network_error" -> "网络不通：${t.message}"
            "code_not_found" -> "配对码不存在（或服务器不对）"
            "code_used" -> "配对码已被使用，请重新生成"
            "code_expired" -> "配对码已过期，请重新生成"
            "invalid_code" -> "配对码格式不对"
            "invalid_token" -> "设备 token 无效，请重新配对"
            "ts_skew" -> "设备与服务端时间相差过大，请校准时间"
            "empty_body", "invalid_response" -> "服务端响应异常（可能不是 vkey 服务）"
            else -> t.message ?: t.code
        }
        return hint
    }
    if (t is IllegalArgumentException) return t.message ?: "输入不合法"
    return t.message ?: t.javaClass.simpleName
}
